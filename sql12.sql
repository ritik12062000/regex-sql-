-- Running total using ORDER BY
SELECT *,
       SUM(amount) OVER(ORDER BY amount) AS running_total
FROM sales;



-- Running total from first row to current row
SELECT *,
       SUM(amount) OVER(
           ORDER BY sale_date
           ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS running_total
FROM sales;



-- Sum from first row to next row
SELECT *,
       SUM(amount) OVER(
           ORDER BY sale_date
           ROWS BETWEEN UNBOUNDED PRECEDING AND 1 FOLLOWING
       ) AS sum_result
FROM sales;



-- View complete table
SELECT * 
FROM sales;



-- Sum of current row and previous 2 rows
SELECT *,
       SUM(amount) OVER(
           ORDER BY sale_date
           ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
       ) AS moving_sum
FROM sales;



-- Calculate sum of current row and next row
SELECT 
    id,
    sale_date,
    amount,
    SUM(amount) OVER(
        ORDER BY sale_date
        ROWS BETWEEN CURRENT ROW AND 1 FOLLOWING
    ) AS current_sum
FROM sales;

 


























































































































































































































































































































































































































































































































































 